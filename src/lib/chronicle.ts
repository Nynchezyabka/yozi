const GROUP: Record<ActKind, string> = { snack: "food", lunch: "food", warm: "food", soft: "food", water: "water", sleep: "sleep", rest: "rest", walk: "walk" };

export function chronicleLine(kind: ActKind | "idle", rnd: number): string {
  const list = LINES[kind === "idle" ? "idle" : GROUP[kind]]!;
  return list[Math.floor(rnd * list.length) % list.length]!;
}
